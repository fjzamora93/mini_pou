"""Builds the tower-defense map assets from the raw map screenshot.

Outputs:
  assets/images/maps/jungle_camp.png                  cropped, clean map image
  lib/features/defense/domain/maps/jungle_camp.dart   placement grid + routes

Placement grid: one char per CELL x CELL block of map pixels.
  '#' = grass where the pet can stand, '.' = anything else (path, sand,
  buildings, bushes, palms, rocks...). A cell counts as grass only when
  almost all of its pixels are the flat grass colour.

Usage:  python3 tool/defense_map.py
"""

import os

import numpy as np
from PIL import Image

SRC = 'assets/images/maps/Screenshot from 2026-11-22 09-47-17.png'
OUT_IMG = 'assets/images/maps/jungle_camp.png'
OUT_DART = 'lib/features/defense/domain/maps/jungle_camp.dart'

# The screenshot has a white strip on top and a grey one at the bottom.
CROP = (0, 5, 1528, 819)
CELL = 16
GRASS = (106, 125, 89)
GRASS_TOLERANCE = 30  # sum of |dr|+|dg|+|db|
GRASS_MIN_FRACTION = 0.8

# Path centre lines in cropped-map pixels, traced over the sand path.
# Two entrances (right edge, bottom edge) merge and leave at the bottom-left.
SHARED = [(790, 428), (720, 428), (640, 430), (545, 430), (440, 432),
          (360, 432), (300, 450), (265, 500), (260, 560), (265, 640),
          (265, 700), (240, 750), (150, 790), (60, 800), (-40, 800)]
ROUTES = {
    'east': [(1560, 550), (1520, 550), (1470, 500), (1420, 445), (1360, 415),
             (1290, 410), (1230, 425), (1160, 450), (1080, 440), (1000, 420),
             (920, 415), (840, 425)] + SHARED,
    'south': [(775, 850), (772, 790), (785, 720), (805, 640), (805, 560),
              (795, 490)] + SHARED,
}


def main():
    img = Image.open(SRC).convert('RGB').crop(CROP)
    img.save(OUT_IMG, optimize=True)
    px = np.asarray(img).astype(int)
    h, w, _ = px.shape
    grass = np.abs(px - GRASS).sum(2) < GRASS_TOLERANCE

    rows = []
    for cy in range(0, h - CELL + 1, CELL):
        row = ''
        for cx in range(0, w - CELL + 1, CELL):
            frac = grass[cy:cy + CELL, cx:cx + CELL].mean()
            row += '#' if frac >= GRASS_MIN_FRACTION else '.'
        rows.append(row)

    def pts(route):
        return ', '.join(f'MapPoint({x}, {y})' for x, y in route)

    routes = '\n'.join(
        f"    MapRoute('{name}', [{pts(r)}]),"
        for name, r in ROUTES.items())
    grid = '\n'.join(f"    '{r}'," for r in rows)

    os.makedirs(os.path.dirname(OUT_DART), exist_ok=True)
    with open(OUT_DART, 'w') as f:
        f.write(f"""// GENERATED by tool/defense_map.py — do not edit by hand.
// ignore_for_file: require_trailing_commas

import '../entities/defense_map_entity.dart';

/// Jungle camp: two entrances (east, south) merging into one exit at the
/// bottom-left. '#' cells are grass where the pet may be placed.
const jungleCampMap = DefenseMapEntity(
  image: 'maps/jungle_camp.png',
  width: {w},
  height: {h},
  cellSize: {CELL},
  routes: [
{routes}
  ],
  placementGrid: [
{grid}
  ],
);
""")
    print(f'map {w}x{h}, grid {len(rows[0])}x{len(rows)}, '
          f'placeable {sum(r.count("#") for r in rows)} cells')


if __name__ == '__main__':
    main()
